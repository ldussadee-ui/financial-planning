// Translates a stored label (category name, goal type, ...) for display
// only — falls back to the original string when there's no known
// translation (e.g. a custom category the user typed themselves).
export function translateLabel(label: string, lang: Language, map: Record<string, string>): string {
  if (lang !== "en") return label;
  return map[label] ?? label;
}
